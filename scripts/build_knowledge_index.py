"""Build knowledge/index.md: one table per rule file listing every rule.

It also rewrites the counts line of README.md (rule files, graded rules, sources) from the same
numbers, when a README.md sits beside the knowledge folder.

Usage: uv run python scripts/build_knowledge_index.py [--knowledge-dir DIR]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from coach.knowledge import GRADES, KNOWLEDGE_DIR, checked_date, iter_rules, read, rule_files

SOURCE_HEADING_RE = re.compile(r"^### (S\d+)\s*$", re.MULTILINE)
# "4 rule files (names), 459 graded rules, 859 sources" in the README's folder table
README_COUNTS_RE = re.compile(r"\d+ rule files \(([^)]*)\), \d+ graded rules, \d+ sources")

HEADER = """# Knowledge index

> Generated by `scripts/build_knowledge_index.py`; do not edit by hand. One row per rule.
> Read a rule or a whole section with `coach.knowledge.section(file, heading)` (or the `Line`
> number); look a source up with `grep -n -A6 '^### S123$' knowledge/sources.md`.
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def build_index(knowledge_dir: Path = KNOWLEDGE_DIR) -> str:
    parts = [HEADER]
    for path in rule_files(knowledge_dir):
        text = read(path)
        rules = list(iter_rules(text))
        checked = checked_date(text)
        checked_note = f"Evidence checked on {checked}" if checked else "no checked date"
        parts.append(f"\n## {path.name}\n\n{checked_note}, {len(rules)} rules.\n")
        parts.append("\n| Line | Section | Rule | Grade | Sources |\n|---|---|---|---|---|\n")
        for rule in rules:
            cells = [
                str(rule.line),
                _cell(rule.section),
                _cell(rule.heading),
                rule.grade or "?",
                ", ".join(rule.source_ids),
            ]
            parts.append("| " + " | ".join(cells) + " |\n")
    return "".join(parts)


def counts(knowledge_dir: Path) -> dict[str, int]:
    sources = SOURCE_HEADING_RE.findall(read(Path(knowledge_dir) / "sources.md"))
    result = {"sources": len(sources), "rules": 0} | dict.fromkeys(GRADES, 0)
    for path in rule_files(knowledge_dir):
        for rule in iter_rules(read(path)):
            result["rules"] += 1
            if rule.grade in GRADES:
                result[rule.grade] += 1
    return result


def readme_path(knowledge_dir: Path) -> Path:
    return Path(knowledge_dir).resolve().parent / "README.md"


def readme_with_counts(text: str, knowledge_dir: Path) -> str | None:
    """`text` with the counts line brought up to date, or None when it has no counts line."""
    totals = counts(knowledge_dir)
    files = len(rule_files(knowledge_dir))

    def line(match: re.Match) -> str:
        return (
            f"{files} rule files ({match.group(1)}), {totals['rules']} graded rules, "
            f"{totals['sources']} sources"
        )

    new, found = README_COUNTS_RE.subn(line, text, count=1)
    return new if found else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--knowledge-dir", type=Path, default=KNOWLEDGE_DIR)
    args = parser.parse_args(argv)
    index = args.knowledge_dir / "index.md"
    index.write_text(build_index(args.knowledge_dir), encoding="utf-8")
    print(f"wrote {index}")
    readme = readme_path(args.knowledge_dir)
    if readme.exists():
        updated = readme_with_counts(read(readme), args.knowledge_dir)
        if updated is None:
            print(
                f"{readme} has no counts line (N rule files (...), N graded rules)", file=sys.stderr
            )
            return 1
        readme.write_text(updated, encoding="utf-8")
        print(f"updated the counts in {readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
